from game_logic import (
    can_exit,
    is_level_clear,
    count_arrows,
    is_solvable
)


# -------------------------------------------------
# T01：前方无遮挡，箭头应该可以飞出去
# -------------------------------------------------

def test_arrow_can_exit():

    board = [
        [".", ".", "."],
        [".", "R", "."],
        [".", ".", "."]
    ]

    assert can_exit(
        board,
        1,
        1
    ) is True


# -------------------------------------------------
# T02：前方存在其他箭头，不能飞出去
# -------------------------------------------------

def test_arrow_is_blocked():

    board = [
        [".", ".", "."],
        ["R", ".", "U"],
        [".", ".", "."]
    ]

    assert can_exit(
        board,
        1,
        0
    ) is False


# -------------------------------------------------
# T03：位于边界并且朝外，可以直接飞出去
# -------------------------------------------------

def test_edge_arrow():

    board = [
        ["U", ".", "."],
        [".", ".", "."],
        [".", ".", "."]
    ]

    assert can_exit(
        board,
        0,
        0
    ) is True


# -------------------------------------------------
# T04：空格不能被当作箭头
# -------------------------------------------------

def test_empty_cell():

    board = [
        [".", ".", "."],
        [".", ".", "."],
        [".", ".", "."]
    ]

    assert can_exit(
        board,
        1,
        1
    ) is False


# -------------------------------------------------
# T05：箭头全部清除后应该判定通关
# -------------------------------------------------

def test_level_clear():

    board = [
        [".", "."],
        [".", "."]
    ]

    assert is_level_clear(
        board
    ) is True


# -------------------------------------------------
# T06：还有箭头时不能判定通关
# -------------------------------------------------

def test_level_not_clear():

    board = [
        [".", "R"],
        [".", "."]
    ]

    assert is_level_clear(
        board
    ) is False


# -------------------------------------------------
# T07：正确统计箭头数量
# -------------------------------------------------

def test_count_arrows():

    board = [
        ["R", ".", "U"],
        [".", ".", "."],
        ["L", ".", "D"]
    ]

    assert count_arrows(
        board
    ) == 4


# -------------------------------------------------
# T08：检查一个简单关卡是否可解
# -------------------------------------------------

def test_solvable_level():

    board = [
        ["L", "."],
        [".", "R"]
    ]

    assert is_solvable(
        board
    ) is True